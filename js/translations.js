class LanguageManager {
  constructor() {
    this.currentLang = localStorage.getItem("gbtv_lang") || "mr";
  }

  getLang() {
    return this.currentLang;
  }

  setLang(lang) {
    if (lang !== "mr" && lang !== "en") lang = "mr";
    this.currentLang = lang;
    localStorage.setItem("gbtv_lang", lang);
    document.documentElement.lang = lang;
    this.applyTranslations();
    this.updateToggleUI();

    // Custom event broadcast
    window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang: this.currentLang } }));
  }

  t(key) {
    const dict = GBTV_TRANSLATIONS[this.currentLang] || GBTV_TRANSLATIONS.mr;
    return dict[key] || GBTV_TRANSLATIONS.en[key] || key;
  }

  applyTranslations() {
    const dict = GBTV_TRANSLATIONS[this.currentLang] || GBTV_TRANSLATIONS.mr;

    // Translate textContent with data-i18n
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // Translate innerHTML with data-i18n-html
    document.querySelectorAll("[data-i18n-html]").forEach(el => {
      const key = el.getAttribute("data-i18n-html");
      if (dict[key]) {
        el.innerHTML = dict[key];
      }
    });

    // Translate input placeholders
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (dict[key]) {
        el.placeholder = dict[key];
      }
    });
  }

  updateToggleUI() {
    document.querySelectorAll(".lang-switch-btn, .btn-lang-option").forEach(btn => {
      const lang = btn.getAttribute("data-lang");
      if (lang === this.currentLang) {
        btn.classList.add("active");
      } else {
        btn.classList.remove("active");
      }
    });

    const activeLabel = document.getElementById("active-lang-label");
    if (activeLabel) {
      activeLabel.textContent = this.currentLang === "mr" ? "मराठी" : "English";
    }
  }

  init() {
    this.setLang(this.currentLang);

    // Click handlers for lang toggle buttons
    document.addEventListener("click", (e) => {
      const langBtn = e.target.closest("[data-lang]");
      if (langBtn) {
        const targetLang = langBtn.getAttribute("data-lang");
        if (targetLang) {
          this.setLang(targetLang);
        }
      }

      const langToggleBadge = e.target.closest("#lang-toggle-btn");
      if (langToggleBadge) {
        const nextLang = this.currentLang === "mr" ? "en" : "mr";
        this.setLang(nextLang);
      }
    });
  }
}

window.gbtvLang = new LanguageManager();
document.addEventListener("DOMContentLoaded", () => {
  window.gbtvLang.init();
});
